// Command blqsortgen generates a blqsort (branchless quicksort) specialized
// for one element type and sort key, as a self-contained Go file in your
// package. Specialized code inlines the comparison, which is what makes
// branchless sorting pay off for structs. Measured against slices.SortFunc
// with cmp.Compare on 1M random records: about 3.2x faster on 8-byte records
// with an integer key and 2.1x on 64-byte records (Intel), 4.4x and 1.7x
// (Apple M1). The gain shrinks as records grow, because blqsort moves
// elements more than pdqsort does; from about 32 bytes up, a pdqsort
// specialized the same way is faster.
//
// Add it to your module as a tool, so go run can find it (Go 1.24 or
// later):
//
//	go get -tool github.com/dlm/blqsort/cmd/blqsortgen@v0.1.1
//
// Usage, typically from a go:generate directive:
//
//	//go:generate go run github.com/dlm/blqsort/cmd/blqsortgen -type Person -by=-Age,Name.Last
//
// This writes sort_person_by_age_desc_last_gen.go with
//
//	func sortPersonByAgeDescLast(data []Person)
//
// which sorts by Age (descending), then by Name.Last (ascending).
//
// Flags:
//
//	-type T     element type (required), e.g. Person or *Person
//	-by keys    comma-separated field paths (required); a leading "-" sorts
//	            that key in descending order. Keys must be of ordered types
//	            (integers, floats, strings).
//	-func name  name of the generated function (default sort<T>By<Keys>)
//	-o file     output file (default derived from the function name)
//	-pkg name   package name (default $GOPACKAGE, set by go generate)
//
// The comparison over several keys is generated branch-free, so it stays
// fast on random data. NaN keys are not ordered, and they leave the other
// elements unsorted too: filter them out first. The sort is not stable.
// Every helper in the generated file is suffixed with the function name, so
// several generated sorters can live in one package.
package main

import (
	_ "embed"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
	"unicode"

	"github.com/dlm/blqsort/internal/codegen"
)

// sortSource is blqsort's comparator variant (cmp func(a, b T) int) with
// its helpers; generated by go run ./gen in the repository root.
//
//go:embed sortsource.txt
var sortSource string

//go:embed license.txt
var license string

type key struct {
	path string // field path, e.g. Name.Last
	desc bool
}

var fieldPath = regexp.MustCompile(`^[A-Za-z_]\w*(\.[A-Za-z_]\w*)*$`)

func parseKeys(by string) ([]key, error) {
	var keys []key
	for _, k := range strings.Split(by, ",") {
		k = strings.TrimSpace(k)
		desc := strings.HasPrefix(k, "-")
		k = strings.TrimPrefix(k, "-")
		if !fieldPath.MatchString(k) {
			return nil, fmt.Errorf("invalid key %q: want a field path such as Name or Name.Last", k)
		}
		keys = append(keys, key{k, desc})
	}
	return keys, nil
}

// lessExpr builds the less template ({a}, {b} are the elements) for keys:
// a plain comparison for one key, otherwise the branch-free
// lt1 | eq1&(lt2 | eq2&(...)) on 0/1 integers, since a||b&&c would compile
// to branches on the data.
func lessExpr(keys []key) string {
	lt := func(k key) string {
		if k.desc {
			return "{b}." + k.path + " < {a}." + k.path
		}
		return "{a}." + k.path + " < {b}." + k.path
	}
	if len(keys) == 1 {
		return lt(keys[0])
	}
	expr := "b2i(" + lt(keys[len(keys)-1]) + ")"
	for i := len(keys) - 2; i >= 0; i-- {
		k := keys[i]
		expr = fmt.Sprintf("b2i(%s) | (b2i({a}.%s == {b}.%s) & (%s))", lt(k), k.path, k.path, expr)
	}
	return "(" + expr + ") != 0"
}

func capitalize(s string) string {
	r := []rune(s)
	if len(r) == 0 {
		return s
	}
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// typeName is the bare name of a type expression: *pkg.Person -> Person.
func typeName(t string) string {
	t = strings.TrimLeft(t, "*[]")
	return t[strings.LastIndexByte(t, '.')+1:]
}

func defaultFunc(typ string, keys []key) string {
	var b strings.Builder
	b.WriteString("sort" + capitalize(typeName(typ)) + "By")
	for _, k := range keys {
		b.WriteString(capitalize(k.path[strings.LastIndexByte(k.path, '.')+1:]))
		if k.desc {
			b.WriteString("Desc")
		}
	}
	return b.String()
}

// snake converts sortPersonByAge to sort_person_by_age.
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				b.WriteByte('_')
			}
			r = unicode.ToLower(r)
		}
		b.WriteRune(r)
	}
	return b.String()
}

func describe(keys []key) string {
	var parts []string
	for _, k := range keys {
		if k.desc {
			parts = append(parts, k.path+" (descending)")
		} else {
			parts = append(parts, k.path)
		}
	}
	return strings.Join(parts, ", then ")
}

func generate(pkg, typ, fn string, keys []key, cmdline string) ([]byte, error) {
	const entry = "SortGen" // name of the entry point before renaming
	sp := codegen.Spec{Type: typ, Suffix: "Gen", Less: lessExpr(keys)}
	code, err := sp.Specialize(sortSource)
	if err != nil {
		return nil, err
	}
	code, err = codegen.SetDoc(code, entry, fmt.Sprintf(
		"%s sorts data by %s, with blqsort (a branchless quicksort,\n"+
			"github.com/dlm/blqsort). It is fastest on data in random order; it is\n"+
			"not stable, and NaN keys leave the result unsorted.", fn, describe(keys)))
	if err != nil {
		return nil, err
	}
	tag := capitalize(fn)
	code, err = codegen.Finish(code, entry, func(name string) string {
		if name == entry {
			return fn
		}
		return strings.TrimSuffix(name, "Gen") + tag
	})
	if err != nil {
		return nil, err
	}
	// Comments still use the pre-rename names (sortrGen); match the code.
	genName := regexp.MustCompile(`\b(\w+)Gen\b`)
	lines := strings.Split(code, "\n")
	for i, l := range lines {
		if strings.HasPrefix(strings.TrimSpace(l), "//") {
			lines[i] = genName.ReplaceAllString(l, "${1}"+tag)
		}
	}
	code = strings.Join(lines, "\n")
	notice := "This file contains code from github.com/dlm/blqsort:\n//\n// " +
		strings.ReplaceAll(strings.TrimSpace(license), "\n", "\n// ")
	notice = strings.ReplaceAll(notice, "// \n", "//\n")
	out := codegen.HeaderBy("blqsortgen "+cmdline, pkg, notice, code)
	return format.Source([]byte(out))
}

func main() {
	log := func(format string, args ...any) {
		fmt.Fprintf(os.Stderr, "blqsortgen: "+format+"\n", args...)
		os.Exit(2)
	}
	typ := flag.String("type", "", "element type, e.g. Person or *Person (required)")
	by := flag.String("by", "", `comma-separated key field paths, "-" prefix for descending (required)`)
	fn := flag.String("func", "", "name of the generated function (default sort<T>By<Keys>)")
	out := flag.String("o", "", "output file (default derived from the function name)")
	pkg := flag.String("pkg", os.Getenv("GOPACKAGE"), "package name (default $GOPACKAGE)")
	flag.Parse()
	if *typ == "" || *by == "" || flag.NArg() > 0 {
		flag.Usage()
		os.Exit(2)
	}
	if *pkg == "" {
		log("no package name: use -pkg, or run from go generate")
	}
	keys, err := parseKeys(*by)
	if err != nil {
		log("%v", err)
	}
	if *fn == "" {
		*fn = defaultFunc(*typ, keys)
	}
	if !token(*fn) {
		log("invalid function name %q", *fn)
	}
	if *out == "" {
		*out = snake(*fn) + "_gen.go"
	}
	src, err := generate(*pkg, *typ, *fn, keys, strings.Join(os.Args[1:], " "))
	if err != nil {
		log("%v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log("%v", err)
	}
}

func token(name string) bool {
	return regexp.MustCompile(`^[A-Za-z_]\w*$`).MatchString(name)
}
