package main

import (
	"strings"
	"testing"
)

func TestParseKeys(t *testing.T) {
	keys, err := parseKeys("-Age, Name.Last,ID")
	if err != nil {
		t.Fatal(err)
	}
	want := []key{{"Age", true}, {"Name.Last", false}, {"ID", false}}
	if len(keys) != len(want) {
		t.Fatalf("got %v", keys)
	}
	for i := range want {
		if keys[i] != want[i] {
			t.Fatalf("key %d: got %v, want %v", i, keys[i], want[i])
		}
	}
	for _, bad := range []string{"", "a..b", "1x", "Name()", "-", "a,,b", "x.y-"} {
		if _, err := parseKeys(bad); err == nil {
			t.Errorf("parseKeys(%q): want an error", bad)
		}
	}
}

func TestLessExpr(t *testing.T) {
	for _, c := range []struct {
		by, want string
	}{
		{"ID", "{a}.ID < {b}.ID"},
		{"-ID", "{b}.ID < {a}.ID"},
		{"-Age,Name", "(b2i({b}.Age < {a}.Age) | (b2i({a}.Age == {b}.Age) & (b2i({a}.Name < {b}.Name)))) != 0"},
	} {
		keys, _ := parseKeys(c.by)
		if got := lessExpr(keys); got != c.want {
			t.Errorf("lessExpr(%q) = %s, want %s", c.by, got, c.want)
		}
	}
	keys, _ := parseKeys("A,B,C")
	if got := lessExpr(keys); strings.Contains(got, "||") || strings.Contains(got, "&&") {
		t.Errorf("multi-key comparison must be branch-free: %s", got)
	}
}

func TestNames(t *testing.T) {
	keys, _ := parseKeys("-Age,Name.Last")
	if got := defaultFunc("*pkg.Person", keys); got != "sortPersonByAgeDescLast" {
		t.Errorf("defaultFunc = %s", got)
	}
	if got := snake("sortPersonByAgeDescLast"); got != "sort_person_by_age_desc_last" {
		t.Errorf("snake = %s", got)
	}
}

func TestGenerateSelfContained(t *testing.T) {
	keys, _ := parseKeys("ID")
	src, err := generate("p", "T", "sortT", keys, "-type T -by ID")
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	for _, want := range []string{"package p\n", "func sortT(data []T)", "MIT License", "Code generated by blqsortgen -type T -by ID; DO NOT EDIT."} {
		if !strings.Contains(s, want) {
			t.Errorf("generated code lacks %q", want)
		}
	}
	if strings.Contains(s, "blqsort\"") || strings.Contains(s, "cmp func(") {
		t.Errorf("generated code should neither import blqsort nor take a comparator")
	}
}
