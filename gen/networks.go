package main

import (
	"fmt"
	"regexp"
	"strings"
)

const letters = "abcdefghijklmnopqrstuvwxyz"

// network returns the parameters and compare-exchange pairs of a sort2-based
// macro (sortN, med5, med7) in blqsort.h.
func network(header, name string) (params []string, pairs [][2]string) {
	m := regexp.MustCompile(`(?s)#define ` + name + `\(([^)]*)\) do \{(.*?)\} while\s*\(0\)`).FindStringSubmatch(header)
	if m == nil {
		fail("networks: macro %s not found", name)
	}
	for _, p := range strings.Split(m[1], ",") {
		params = append(params, strings.TrimSpace(p))
	}
	if name == "sort2" { // the C primitive itself, not a network of sort2 calls
		return params, [][2]string{{"a", "b"}}
	}
	for _, p := range regexp.MustCompile(`sort2\(\s*(\w)\s*,\s*(\w)\s*\)`).FindAllStringSubmatch(m[2], -1) {
		pairs = append(pairs, [2]string{p[1], p[2]})
	}
	return params, pairs
}

// genNetworks emits the sorting networks (sizes 2..18) and median networks
// of blqsort.h as Go: the ordered variant (s2 on cmp.Ordered) when fn is
// false, the comparator variant (s2Func with cmp) when it is true.
func genNetworks(header, pkg string, fn bool) string {
	tp, sfx, cmpParam, cmpArg, lead := "[T cmp.Ordered]", "", "", "", ""
	s2 := func(x, y string) string { return fmt.Sprintf("s2(%s, %s)", x, y) }
	if fn {
		tp, sfx, cmpParam, cmpArg, lead = "[T any]", "Func", ", cmp func(a, b T) int", ", cmp", "cmp func(a, b T) int, "
		s2 = func(x, y string) string { return fmt.Sprintf("s2Func(cmp, %s, %s)", x, y) }
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("// Code generated by go run ./gen from blqsort.h (chkas/blqsort, MIT); DO NOT EDIT.")
	w("")
	w("package %s", pkg)
	w("")
	if !fn {
		w(`import "cmp"`)
		w("")
	}
	for n := 2; n <= 18; n++ {
		params, pairs := network(header, fmt.Sprintf("sort%d", n))
		if strings.Join(params, "") != letters[:n] {
			fail("networks: sort%d has parameters %v", n, params)
		}
		vs := strings.Join(params, ", ")
		idx := make([]string, n)
		for i := range idx {
			idx[i] = fmt.Sprintf("v[%d]", i)
		}
		w("func sort%d%s%s(v []T%s) {", n, sfx, tp, cmpParam)
		w("\t_ = v[%d]", n-1)
		w("\t%s := %s", vs, strings.Join(idx, ", "))
		for _, p := range pairs {
			w("\t%s, %s = %s", p[0], p[1], s2(p[0], p[1]))
		}
		w("\t%s = %s", strings.Join(idx, ", "), vs)
		w("}")
		w("")
	}
	for _, med := range []struct {
		name string
		n    int
	}{{"med5", 5}, {"med7", 7}} {
		_, pairs := network(header, med.name)
		vs := strings.Join(strings.Split(letters[:med.n], ""), ", ")
		w("func %s%s%s(%s%s T) (T%s) {", med.name, sfx, tp, lead, vs, strings.Repeat(", T", med.n-1))
		for _, p := range pairs {
			w("\t%s, %s = %s", p[0], p[1], s2(p[0], p[1]))
		}
		w("\treturn %s", vs)
		w("}")
		w("")
	}
	w("func sortingNetwork%s%s(v []T%s) {", sfx, tp, cmpParam)
	w("\tswitch len(v) {")
	for n := 2; n <= 18; n++ {
		w("\tcase %d:\n\t\tsort%d%s(v%s)", n, n, sfx, cmpArg)
	}
	w("\t}")
	w("}")
	return b.String()
}
