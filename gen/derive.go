package main

import (
	"regexp"
	"strings"
)

// deriveFunc derives func_gen.go (SortFunc, the cmp func(a, b T) int
// variant) from blqsort.go: every < on elements becomes cmp(x, y) < 0, and
// internal functions get a Func suffix and a trailing cmp parameter.
// specialize then turns that file into the other variants.
func deriveFunc(src string) string {
	body := between(src, "func heapSort", "// Sort sorts data in ascending order.")

	reps := [][2]string{
		{"data[i] < data[i-1]", "cmp(data[i], data[i-1]) < 0"},
		{"data[i-1] < data[i]", "cmp(data[i-1], data[i]) < 0"},
		{"[T cmp.Ordered]", "[T any]"},
		{"a[child] < a[child+1]", "cmp(a[child], a[child+1]) < 0"},
		{"!(k < a[child])", "cmp(k, a[child]) >= 0"},
		{"x < piv", "cmp(x, piv) < 0"},
		{"a[left] < piv", "cmp(a[left], piv) < 0"},
		{"!(piv < a[p])", "cmp(piv, a[p]) >= 0"},
		{"med5(", "med5Func(cmp, "},
		{"med7(", "med7Func(cmp, "},
		{"sortingNetwork(a[left : right+1])", "sortingNetworkFunc(a[left:right+1], cmp)"},
		{"sortingNetwork(data)", "sortingNetworkFunc(data, cmp)"},
		{"slices.Sort(data)", "slices.SortFunc(data, cmp)"},
		{"// blqSort is the entry point after NaN handling. The comparator variants\n" +
			"// are derived from everything above this point plus this function.\n",
			"// SortFunc sorts data in ascending order as determined by cmp, like\n" +
				"// slices.SortFunc. It is only fast if cmp compiles to branch-free code;\n" +
				"// cmp.Compare does not (it branches on the data). Prefer SortByKey or\n" +
				"// SortLess.\n"},
		{"func blqSort[T any](data []T)", "func SortFunc[T any](data []T, cmp func(a, b T) int)"},
	}
	for _, r := range reps {
		if !strings.Contains(body, r[0]) {
			fail("derive: pattern not found: %q", r[0])
		}
		body = strings.ReplaceAll(body, r[0], r[1])
	}

	internal := []string{"heapSort", "partitionSmall", "partition", "smallSort", "sortr", "scanOrder"}
	for _, name := range internal {
		body = regexp.MustCompile(`\b`+name+`\b`).ReplaceAllString(body, name+"Func")
	}
	alt := strings.Join(internal, "|")
	// Add the cmp parameter to every internal declaration ...
	body = regexp.MustCompile(`(func (?:`+alt+`)Func\[T any\]\([^)]*)\)`).ReplaceAllString(body, "${1}, cmp func(a, b T) int)")
	// ... and the cmp argument to every internal call (not the declarations,
	// which RE2 cannot exclude with a lookbehind, hence the explicit check).
	call := regexp.MustCompile(`\b((?:` + alt + `)Func)\(([^()]*(?:\([^()]*\)[^()]*)*)\)`)
	var out strings.Builder
	last := 0
	for _, m := range call.FindAllStringSubmatchIndex(body, -1) {
		whole, name, args := body[m[0]:m[1]], body[m[2]:m[3]], body[m[4]:m[5]]
		out.WriteString(body[last:m[0]])
		if strings.HasSuffix(body[:m[0]], "func ") || strings.HasSuffix(args, "cmp func(a, b T) int") {
			out.WriteString(whole)
		} else {
			out.WriteString(name + "(" + args + ", cmp)")
		}
		last = m[1]
	}
	out.WriteString(body[last:])
	body = out.String()

	// Any comparison left without cmp( is probably an element comparison the
	// rules above missed; the allowed ones compare indices and counters.
	cmpLike := regexp.MustCompile(`[^<]<[^-<=]`)
	indexCmp := regexp.MustCompile(`\b(n|j\*2\+1|child\+1|i|mid|right|left|lwr|sw|p|unroll|partszm1|rwr|badLimit|limit|runs|turns)\b\s*<`)
	var leftover []string
	for _, l := range strings.Split(body, "\n") {
		if cmpLike.MatchString(l) && !strings.Contains(l, "cmp(") && !indexCmp.MatchString(l) {
			leftover = append(leftover, l)
		}
	}
	if len(leftover) > 0 {
		fail("derive: unconverted element comparisons?\n%s", strings.Join(leftover, "\n"))
	}

	return `// Code generated by go run ./gen from blqsort.go; DO NOT EDIT.

// Comparator variant of blqsort.go, mirroring slices.SortFunc.

package blqsort

import "slices"

// s2Func is the compare-exchange used by the comparator sorting networks.
func s2Func[T any](cmp func(a, b T) int, x, y T) (T, T) {
	if cmp(y, x) < 0 {
		return y, x
	}
	return x, y
}

` + body
}

// between returns src from the first start (inclusive) to end (exclusive).
func between(src, start, end string) string {
	i := strings.Index(src, start)
	j := strings.Index(src, end)
	if i < 0 || j < i {
		fail("markers %q .. %q not found", start, end)
	}
	return src[i:j]
}
